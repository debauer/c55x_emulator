"""Linker command file of the Doom port: linkcmd.py OUT.cmd OBJ...

Before CPU revision 3.0 no data section may cross a 64 KB boundary, but Doom has about 200 KB
of variables and 66 KB of constants. So the .bss, .data and .const input sections of the object
files are packed into output sections of at most 64 KB (.bss0, .bss1 ...), each in its own
64 KB block of memory (the generated section names have no meaning for the code)."""

import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from c55x_emu.coff import FILE_HDR, SCN_HDR, SYM, _name          # noqa: E402

BLOCK = 0x10000
CAPACITY = BLOCK - 0x20
KINDS = {".const": 0x100000, ".data": 0x180000, ".bss": 0x200000}   # first block of each kind
HEADER = """/* Memory layout of the Doom port (byte addresses; the emulator has one flat 16 MB memory),
 * generated by linkcmd.py. ROM model: variables are initialised by _c_int00 from .cinit.
 *   0x040000  code, .cinit tables
 *   0x100000  .const blocks, 0x180000 .data blocks, 0x200000 .bss blocks (64 KB each)
 *   0x510000  Doom zone (set up by the port), up to 0xBFDFFF
 *   0xBFE000  WAD file, packed 2 bytes per word (loaded with --load)
 * 0x500000..0x507FFF is the CE1 window of ATA and LCD, never used for memory. */
-c
-e _zen_reset
-stack 0x2000
-sysstack 0x400
-heap 0xF000
"""


def section_sizes(path):
    data = path.read_bytes()
    magic, nscns, _, symptr, nsyms, opthdr, *_ = FILE_HDR.unpack_from(data, 0)
    strings = data[symptr + nsyms * SYM.size:]
    sizes = {}
    for i in range(nscns):
        raw, _, _, size, *_ = SCN_HDR.unpack_from(data, FILE_HDR.size + opthdr + i * SCN_HDR.size)
        sizes[_name(raw, strings)] = size
    return sizes


def pack(objects):
    """-> {kind: [[(object, input section) per block]]}: every input section of the kind
    (.const:.string, ...) is placed on its own, first fit"""
    blocks = {}
    for kind in KINDS:
        items = sorted(((size, p.name, name) for p in objects
                        for name, size in section_sizes(p).items()
                        if size and (name == kind or name.startswith(kind + ":"))), reverse=True)
        free = []
        for size, obj, name in items:
            if size > CAPACITY:
                sys.exit(f"{obj}: {name} is {size} bytes, more than one 64 KB block")
            for block in free:
                if block[0] >= size:
                    block[0] -= size
                    block[1].append((obj, name))
                    break
            else:
                free.append([CAPACITY - size, [(obj, name)]])
        blocks[kind] = [entries for _, entries in free]
    return blocks


def main():
    out, objects = Path(sys.argv[1]), [Path(p) for p in sys.argv[2:]]
    blocks = pack(objects)
    memory = ["    VECT (RX)   : origin = 0x00000100, length = 0x00000200",
              "    DARAM (RW)  : origin = 0x00002000, length = 0x0000E000",
              "    ROM (RX)    : origin = 0x00040000, length = 0x000A0000",
              "    HEAP (RW)   : origin = 0x000E0000, length = 0x00010000",
              "    REST (RW)   : origin = 0x000F0000, length = 0x00010000"]
    sections = ["    .vectors  : {} > VECT", "    .text     : {} > ROM", "    .cinit    : {} > ROM",
                "    .switch   : {} > ROM"]
    for kind, base in KINDS.items():
        for i, names in enumerate(blocks[kind]):
            region = f"{kind[1:].upper()}{i}"
            memory.append(f"    {region} (RW) : origin = 0x{base + i * BLOCK:08x}, length = 0x{BLOCK:08x}")
            files = " ".join(f"{obj}({name})" for obj, name in names)
            sections.append(f"    {kind}{i} : {{ {files} }} > {region}")
        sections.append(f"    {kind} : {{}} > REST")           # what is left, e.g. the C library
    sections += ["    .sysmem   : {} > HEAP", "    .stack    : {} > DARAM", "    .sysstack : {} > DARAM"]
    out.write_text(HEADER + "MEMORY\n{\n" + "\n".join(memory) + "\n}\nSECTIONS\n{\n"
                   + "\n".join(sections) + "\n}\n")
    print({k: len(v) for k, v in blocks.items()})


if __name__ == "__main__":
    main()
